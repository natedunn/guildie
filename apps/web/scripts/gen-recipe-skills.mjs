// Writes apps/web/convex/shared/recipeSkills.generated.ts: for every
// profession recipe, the skill levels where it turns yellow and grey, read from WoW:
// Forever's own game data (its DB2 tables, as published per build by
// wago.tools). Blizzard's web API has none of this.
//
//   node apps/web/scripts/gen-recipe-skills.mjs                 # latest Forever build
//   node apps/web/scripts/gen-recipe-skills.mjs --build 1.60.1.70959
//   node apps/web/scripts/gen-recipe-skills.mjs --summary out.md # also write what changed (markdown)
//   node apps/web/scripts/gen-recipe-skills.mjs --check          # exit 1 if the file would change
//
// How it reads the tables:
// - SkillLine: the professions are the skill lines with a tier under them
//   (Tailoring 197 has "Tailoring" 2948, ParentSkillLineID 197), leaving out
//   "[DNT]" test lines. Their names are the ones Blizzard's API uses.
// - SkillLineAbility: one row per recipe. Its ID is Blizzard's recipe id
//   (/data/wow/recipe/{id}; recipes.recipeId). TrivialSkillLineRankLow is
//   where the recipe turns yellow, TrivialSkillLineRankHigh where it turns
//   grey (no more skill-ups); green starts halfway between (shared/recipeSkills.ts).
//   Rows with no grey level (abilities such as Find Herbs) are left out.
//   MinSkillLineRank (the skill needed to learn it) isn't read: nearly every
//   row says 1, since trainers' requirements live on the server, and the few
//   that don't are Classic's numbers that Forever didn't update (Heavy
//   Sharpening Stone: 125, though it turns yellow at 100).
// - SpellName: the recipe's name, for reading the file and the summaries.
//   A row whose spell isn't in the build's SpellName is left out: the game
//   can't show it, so it's a leftover (Forever dropped Classic's Minor
//   Healing Potion recipe, spell 2330, but kept its SkillLineAbility row).
//
// Output is deterministic (sorted; stamped with the build's own date), so an
// unchanged build writes an identical file. .github/workflows/game-data.yml
// runs this daily and opens a PR on change.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { arg as argOf, buildInfo, format, latestBuild, PRODUCT, table, withoutStamp } from "./lib/wago.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, "../convex/shared/recipeSkills.generated.ts");

const args = process.argv.slice(2);
const arg = (name) => argOf(args, name);

/** Profession name -> recipes sorted by yellow level, then name, then id. */
export function compute({ skillLines, skillLineAbility, spellNames }) {
	const tiers = new Set(skillLines.filter((s) => s.ParentSkillLineID !== "0").map((s) => s.ParentSkillLineID));
	const professions = new Map(
		skillLines
			.filter((s) => s.ParentSkillLineID === "0" && tiers.has(s.ID) && !s.DisplayName_lang.includes("[DNT]"))
			.map((s) => [s.ID, s.DisplayName_lang]),
	);
	const names = new Map(spellNames.map((s) => [s.ID, s.Name_lang]));
	const out = {};
	for (const r of skillLineAbility) {
		const profession = professions.get(r.SkillLine);
		const grey = Number(r.TrivialSkillLineRankHigh);
		const name = names.get(r.Spell);
		if (!profession || !grey || !name) continue;
		(out[profession] ??= []).push({
			id: Number(r.ID),
			name,
			yellow: Number(r.TrivialSkillLineRankLow),
			grey,
		});
	}
	const sorted = {};
	for (const name of Object.keys(out).sort()) {
		sorted[name] = out[name].sort((a, b) => a.yellow - b.yellow || a.name.localeCompare(b.name) || a.id - b.id);
	}
	return sorted;
}

function render(build, professions) {
	const date = (build.created_at || "").slice(0, 10);
	const out = [];
	out.push("// GENERATED by apps/web/scripts/gen-recipe-skills.mjs. Do not edit by hand:");
	out.push("// run the script (or let .github/workflows/game-data.yml do it). Read it");
	out.push("// through shared/recipeSkills.ts.");
	out.push("//");
	out.push(`// WoW: Forever (${PRODUCT}) build ${build.version}${date ? ` of ${date}` : ""}, from the game's`);
	out.push("// SkillLine, SkillLineAbility and SpellName tables as published by wago.tools.");
	out.push("// Per profession, every recipe that gives skill-ups: `id` is Blizzard's");
	out.push("// recipe id, `yellow` and `grey` the skill where it turns yellow and grey.");
	out.push("");
	out.push("export type GeneratedRecipeSkill = { id: number; name: string; yellow: number; grey: number };");
	out.push("");
	out.push(
		`export const RECIPE_SKILLS_BUILD = { product: ${JSON.stringify(PRODUCT)}, version: ${JSON.stringify(build.version)}, date: ${JSON.stringify(date)} } as const;`,
	);
	out.push("");
	out.push("export const GENERATED_RECIPE_SKILLS: Record<string, GeneratedRecipeSkill[]> = {");
	for (const [profession, recipes] of Object.entries(professions)) {
		out.push(`\t${JSON.stringify(profession)}: [`);
		for (const r of recipes) {
			out.push(`\t\t{ id: ${r.id}, name: ${JSON.stringify(r.name)}, yellow: ${r.yellow}, grey: ${r.grey} },`);
		}
		out.push("\t],");
	}
	out.push("};");
	out.push("");
	return out.join("\n");
}

const levels = (r) => `${r.yellow}/${r.grey}`;

/** Markdown: what changed per profession between two versions of the data. */
export function summarize(before, after) {
	const lines = [];
	lines.push(
		before
			? `Build ${before.build.version} → **${after.build.version}**${after.build.date ? ` (${after.build.date})` : ""}.`
			: `Build **${after.build.version}**.`,
	);
	lines.push("");
	lines.push("Recipe skill levels as `yellow/grey` (green starts halfway between).");
	lines.push("");
	let changes = 0;
	const professions = [...new Set([...Object.keys(before?.professions ?? {}), ...Object.keys(after.professions)])];
	for (const profession of professions.sort()) {
		const a = new Map((before?.professions[profession] ?? []).map((r) => [r.id, r]));
		const b = new Map((after.professions[profession] ?? []).map((r) => [r.id, r]));
		const diffs = [];
		for (const [id, r] of b) {
			const old = a.get(id);
			if (!old) diffs.push(`+ ${r.name}: ${levels(r)}`);
			else if (levels(old) !== levels(r)) diffs.push(`~ ${r.name}: ${levels(old)} → ${levels(r)}`);
		}
		for (const [id, r] of a) if (!b.has(id)) diffs.push(`- ${r.name} (was ${levels(r)})`);
		if (!diffs.length) continue;
		changes += diffs.length;
		lines.push(`**${profession}** (${diffs.length})`);
		lines.push("");
		// A first run lists everything; keep the summary readable.
		const shown = before ? diffs : diffs.slice(0, 10);
		for (const d of shown) lines.push(`- \`${d}\``);
		if (shown.length < diffs.length) lines.push(`- …and ${diffs.length - shown.length} more`);
		lines.push("");
	}
	if (!changes) lines.push("No recipe's levels changed (only names).");
	return lines.join("\n");
}

async function main() {
	const wanted = arg("--build");
	const build = wanted ? await buildInfo(wanted) : await latestBuild();
	const [skillLines, skillLineAbility, spellNames] = await Promise.all([
		table("SkillLine", build.version),
		table("SkillLineAbility", build.version),
		table("SpellName", build.version),
	]);
	if (!skillLines.length || !skillLineAbility.length || !spellNames.length)
		throw new Error(`empty tables for build ${build.version}`);
	const professions = compute({ skillLines, skillLineAbility, spellNames });
	if (Object.keys(professions).length < 10)
		throw new Error(`only ${Object.keys(professions).length} professions in build ${build.version}`);
	const text = format(render(build, professions), OUT);
	const old = existsSync(OUT) ? readFileSync(OUT, "utf8") : undefined;
	// A new build with the same data leaves the file (and its stamp) alone.
	const changed = !old || withoutStamp(old) !== withoutStamp(text);

	const summaryPath = arg("--summary");
	if (summaryPath) {
		let before;
		if (old) {
			const mod = await import(`${pathToFileURL(OUT).href}?t=${Date.now()}`);
			before = { build: mod.RECIPE_SKILLS_BUILD, professions: mod.GENERATED_RECIPE_SKILLS };
		}
		const after = { build: { version: build.version, date: (build.created_at || "").slice(0, 10) }, professions };
		writeFileSync(summaryPath, `${summarize(before, after)}\n`);
	}
	if (args.includes("--check")) {
		console.log(changed ? `would change (build ${build.version})` : `up to date (build ${build.version})`);
		process.exit(changed ? 1 : 0);
	}
	if (changed) writeFileSync(OUT, text);
	console.log(`${changed ? "wrote" : "unchanged:"} ${OUT} (build ${build.version})`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	main().catch((error) => {
		console.error(error);
		process.exit(1);
	});
}
